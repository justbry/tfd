/** A file `bun model/build.ts` writes: `name` inside the output directory. */
type GeneratedFile = { name: string; content: string };

const generatedNote =
	"Generated by bun model/build.ts from model/ledger.v1.json. Do not edit.";

// ---- The model facts the outputs share
/** The disclosure classes in the schema's order (the disclosure file's `classes` keys). */
const classOrder = modelSchema.$defs.measure.properties.disclosure.properties
	.class.enum as ResolvedMeasure["disclosure"]["class"][];
const formats = modelSchema.$defs.measure.properties.format.enum;
const detailSteps = modelSchema.$defs.dimension.properties.need.enum;

// ---- disclosure-classes.v1.json
/** The disclosure file's class table: each class's spec KPIs, in model (spec) order. */
export const disclosureClassesOf = ({
	measures,
}: ResolvedModel): Record<string, string[]> =>
	Object.fromEntries(
		classOrder.map((kpiClass) => [
			kpiClass,
			measures
				.filter(
					(measure) =>
						measure.source === "kpiSpec" &&
						measure.disclosure.class === kpiClass,
				)
				.map((measure) => measure.id),
		]),
	);

