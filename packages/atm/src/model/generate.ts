/**
 * What `bun model/build.ts` writes, on demand, from the ledger model (`model/ledger.v1.json`): the KPI document's
 * catalog and the derived KPIs (the Worker computes the same two in-process through `src/ledger/kpi-catalog.ts`), the
 * disclosure file's class table, the OpenAPI components of the KPI document and the model's JSON-LD context. Pure: the
 * resolved model in, `{ name, content }` out. Nothing it makes is committed; the tests compute each value in memory.
 * Not Worker code.
 */
