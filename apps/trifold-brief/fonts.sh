#!/usr/bin/env bash
# Write _fonts.css: the brand's three typefaces (Fraunces, Inter, JetBrains Mono; Latin, variable weight) as
# base64 @font-face rules, so every rendered page embeds them and loads nothing from outside.
# The woff2 files and their SIL Open Font License 1.1 texts are in fonts/. Run after replacing a font file.
set -euo pipefail

cd "$(dirname "$0")"

face() {
  local family="$1" file="$2" weights="$3" copyright="$4"
  printf '/* %s: %s. SIL Open Font License 1.1, text in fonts/. */\n' "$family" "$copyright"
  printf '@font-face {\n  font-family: "%s";\n  font-style: normal;\n  font-weight: %s;\n  font-display: swap;\n' "$family" "$weights"
  printf '  src: url("data:font/woff2;base64,%s") format("woff2");\n}\n' "$(base64 < "fonts/$file" | tr -d '\n')"
}

{
  printf '/* Generated by fonts.sh. Do not edit by hand. */\n'
  face "Fraunces" fraunces.woff2 "100 900" "Copyright 2020 The Fraunces Project Authors (github.com/undercasetype/Fraunces)"
  face "Inter" inter.woff2 "100 900" "Copyright 2016 The Inter Project Authors (github.com/rsms/inter)"
  face "JetBrains Mono" jetbrains-mono.woff2 "100 800" "Copyright 2020 The JetBrains Mono Project Authors (github.com/JetBrains/JetBrainsMono)"
} > _fonts.css

echo "wrote _fonts.css"
